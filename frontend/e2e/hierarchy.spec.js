import { expect, reseed, signIn, test, USERS } from './helpers.js'

test.beforeEach(() => {
  reseed()
})

async function addManager(page, path, button, name, parentLabel, parentOption) {
  await page.goto(path)
  await page.getByRole('button', { name: button }).click()
  const modal = page.locator('.modal.show')
  await modal.getByLabel('Name').fill(name)
  if (parentLabel) {
    await modal.getByLabel(parentLabel).selectOption({ label: parentOption })
    if (path.includes('second-line') || path.includes('first-line')) await modal.getByRole('checkbox', { name: 'Gujarat' }).check()
  } else {
    await modal.getByLabel('Employee Code').fill('001')
    await modal.getByLabel('Email').fill(`${name.toLowerCase().replace(/\s+/g, '-')}@example.test`)
    await modal.getByLabel('Phone Number').fill('9000000181')
    await modal.getByRole('checkbox', { name: 'Gujarat' }).check()
  }
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('tbody tr', { hasText: name })).toHaveCount(1)
}

test('the headquarters state list comes from the Location master', async ({ page }) => {
  await signIn(page, USERS.admin)
  await expect(page).toHaveURL('/dashboard')
  await addManager(page, '/sales-office/third-line-managers', 'Add 3rd line manager', 'State Third')
  await addManager(page, '/sales-office/second-line-managers', 'Add 2nd line manager', 'State Second', '3rd Line Manager', 'State Third')
  await addManager(page, '/sales-office/first-line-managers', 'Add 1st line manager', 'State First', '2nd Line Manager', 'State Second (State Third)')
  await page.goto('/sales-office/locations')
  await page.getByRole('button', { name: 'Add location headquarters' }).click()
  const state = page.locator('.modal.show').getByLabel('State')
  await expect(state.locator('option')).toHaveCount(7)
  await expect(state.locator('option', { hasText: 'Gujarat' })).toHaveCount(1)
  await expect(state.locator('option', { hasText: 'Delhi' })).toHaveCount(0)
})

test('the hierarchy page shows the chain from a 3rd line manager down to stockists', async ({ page }) => {
  test.setTimeout(90_000)
  await signIn(page, USERS.admin)
  await expect(page).toHaveURL('/dashboard')

  await addManager(page, '/sales-office/third-line-managers', 'Add 3rd line manager', 'Chain Third')
  await addManager(page, '/sales-office/second-line-managers', 'Add 2nd line manager', 'Chain Second', '3rd Line Manager', 'Chain Third')
  await addManager(page, '/sales-office/first-line-managers', 'Add 1st line manager', 'Chain First', '2nd Line Manager', 'Chain Second (Chain Third)')

  await page.goto('/sales-office/locations')
  await page.getByRole('button', { name: 'Add location headquarters' }).click()
  const locationModal = page.locator('.modal.show')
  await locationModal.getByLabel('State').selectOption('Gujarat')
  await locationModal.getByLabel('Headquarters name').fill('Chain HQ')
  await locationModal.getByLabel('Headquarters address').fill('1 Chain Road')
  await locationModal.getByLabel('Pincode').fill('380001')
  await locationModal.getByLabel('Phone number').fill('9000000201')
  await locationModal.getByLabel('Email').fill('chain-hq@example.test')
  await locationModal.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('table', { name: 'Location headquarters' }).locator('tbody tr', { hasText: 'Chain HQ' })).toContainText('HQ-001')
  await page.reload()
  await expect(page.getByRole('table', { name: 'Location headquarters' }).locator('tbody tr', { hasText: 'Chain HQ' })).toContainText('chain-hq@example.test')
  await page.goto('/sales-office/headquarters')
  await page.getByRole('button', { name: 'Add Headquarters' }).click()
  const hq = page.locator('.modal.show')
  await hq.getByLabel('Location Headquarters').selectOption({ label: 'Chain HQ (Gujarat · HQ-001)' })
  await hq.getByLabel('1st Line Manager').selectOption({ label: 'Chain First' })
  await expect(hq.getByLabel('Headquarters name')).toHaveValue('Chain HQ')
  await expect(hq.getByLabel('Headquarters address')).toHaveAttribute('readonly', '')
  await hq.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('tbody tr', { hasText: 'Chain HQ' })).toHaveCount(1)

  await page.goto('/sales-office/stockists')
  await page.getByRole('button', { name: 'Add stockist' }).click()
  const stockist = page.locator('.modal.show')
  await stockist.getByLabel('Stockist name').fill('Chain Stockist')
  await expect(stockist.getByLabel('Stockist code')).toHaveValue('001')
  await stockist.getByLabel('Headquarters').selectOption({ label: 'Chain HQ (HQ-001)' })
  await stockist.getByLabel('Address').fill('1 Chain Road')
  await stockist.getByLabel('Pincode').fill('380001')
  await stockist.getByLabel('Phone number').fill('12452724')
  await stockist.getByLabel('Email').fill('chain-stockist@example.test')
  await stockist.getByRole('button', { name: 'Save' }).click()
  const stockistRow = page.locator('tbody tr', { hasText: 'Chain Stockist' })
  await expect(stockistRow).toHaveCount(1)
  await expect(page.locator('table thead th')).toHaveText(['Stockist', 'Code', 'Headquarters', 'State', 'Address', 'Pincode', 'Phone Number', 'Email', 'Actions'])
  await expect(stockistRow).toContainText('ST-001')
  await expect(stockistRow).toContainText('Gujarat')
  await expect(stockistRow).toContainText('12452724')
  await page.getByRole('button', { name: 'Filter list' }).click()
  const stockistFilter = page.getByRole('dialog', { name: 'Filter list' })
  await expect(stockistFilter.getByText('State', { exact: true })).toBeVisible()
  await expect(stockistFilter.getByText('Reports To', { exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')

  await page.goto('/sales-office/hierarchy')
  await page.getByLabel('Search the sales office hierarchy').fill('Chain Stockist')
  const branch = page.locator('details.card').filter({ hasText: 'Chain Third' })
  await expect(branch.getByRole('link', { name: 'Chain Second' })).toBeVisible()
  await expect(branch.getByRole('link', { name: 'Chain First' })).toBeVisible()
  await expect(branch.getByRole('link', { name: 'Chain HQ' })).toBeVisible()
  await expect(branch.getByRole('link', { name: 'Chain Stockist' })).toBeVisible()

  await branch.locator('summary').first().click()
  await expect(branch.getByRole('link', { name: 'Chain Stockist' })).toBeHidden()

  await page.goto('/sales-office/stockists')
  await expect(page.getByRole('columnheader', { name: 'Actions' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Chain Stockist' }).click()
  await page.getByRole('dialog', { name: 'Delete stockist' }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.locator('tbody tr', { hasText: 'Chain Stockist' })).toHaveCount(0)
})

test('deleting a headquarters removes the office and keeps the location headquarters', async ({ page }) => {
  test.setTimeout(90_000)
  await signIn(page, USERS.admin)
  await expect(page).toHaveURL('/dashboard')
  await addManager(page, '/sales-office/third-line-managers', 'Add 3rd line manager', 'Delete Third')
  await addManager(page, '/sales-office/second-line-managers', 'Add 2nd line manager', 'Delete Second', '3rd Line Manager', 'Delete Third')
  await addManager(page, '/sales-office/first-line-managers', 'Add 1st line manager', 'Delete First', '2nd Line Manager', 'Delete Second (Delete Third)')

  await page.goto('/sales-office/locations')
  await page.getByRole('button', { name: 'Add location headquarters' }).click()
  const locationModal = page.locator('.modal.show')
  await locationModal.getByLabel('State').selectOption('Gujarat')
  await locationModal.getByLabel('Headquarters name').fill('Delete HQ')
  await locationModal.getByLabel('Headquarters address').fill('1 Delete Road')
  await locationModal.getByLabel('Pincode').fill('380001')
  await locationModal.getByLabel('Phone number').fill('9000000301')
  await locationModal.getByLabel('Email').fill('delete-hq@example.test')
  await locationModal.getByRole('button', { name: 'Save' }).click()

  await page.goto('/sales-office/headquarters')
  await page.getByRole('button', { name: 'Add Headquarters' }).click()
  const hq = page.locator('.modal.show')
  await hq.getByLabel('Location Headquarters').selectOption({ label: 'Delete HQ (Gujarat · HQ-001)' })
  await hq.getByLabel('1st Line Manager').selectOption({ label: 'Delete First' })
  await hq.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('table', { name: 'Headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })).toHaveCount(1)

  await page.getByRole('button', { name: 'Delete Delete HQ' }).click()
  await page.getByRole('dialog', { name: 'Delete headquarters' }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('table', { name: 'Headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('table', { name: 'Headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })).toHaveCount(0)

  await page.goto('/sales-office/locations')
  await expect(page.getByRole('table', { name: 'Location headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })).toContainText('HQ-001')

  await page.goto('/sales-office/headquarters')
  await page.getByRole('button', { name: 'Add Headquarters' }).click()
  const again = page.locator('.modal.show')
  await again.getByLabel('Location Headquarters').selectOption({ label: 'Delete HQ (Gujarat · HQ-001)' })
  await again.getByLabel('1st Line Manager').selectOption({ label: 'Delete First' })
  await again.getByRole('button', { name: 'Save' }).click()
  await page.goto('/sales-office/stockists')
  await page.getByRole('button', { name: 'Add stockist' }).click()
  const stockist = page.locator('.modal.show')
  await stockist.getByLabel('Stockist name').fill('Delete Stockist')
  await stockist.getByLabel('Headquarters').selectOption({ label: 'Delete HQ (HQ-001)' })
  await stockist.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('tbody tr', { hasText: 'Delete Stockist' })).toHaveCount(1)

  await page.goto('/sales-office/headquarters')
  await page.getByRole('button', { name: 'Delete Delete HQ' }).click()
  await page.getByRole('dialog', { name: 'Delete headquarters' }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('table', { name: 'Headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })).toHaveCount(0)

  await page.goto('/sales-office/stockists')
  await expect(page.locator('tbody tr', { hasText: 'Delete Stockist' })).toHaveCount(0)

  await page.goto('/sales-office/locations')
  const locationRow = page.getByRole('table', { name: 'Location headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })
  await expect(locationRow).toContainText('HQ-001')
  await locationRow.getByRole('button', { name: 'Delete Delete HQ' }).click()
  await page.getByRole('dialog', { name: 'Delete location headquarters' }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('table', { name: 'Location headquarters' }).locator('tbody tr', { hasText: 'Delete HQ' })).toHaveCount(0)
})
