import { chooseOption, expect, reseed, signIn, test, USERS } from './helpers.js'

test.beforeEach(() => reseed())

test('employee list saves an empty row and shows a manager dropdown for each level above', async ({ page }) => {
  await signIn(page, USERS.admin)
  await expect(page).toHaveURL('/dashboard')
  await page.goto('/sales-office/employees')
  await expect(page.locator('h1.page-header__title')).toHaveText('Employee List')

  await page.goto('/sales-office/headquarter-list')
  await expect(page.locator('h1.page-header__title')).toHaveText('Headquarter List')
  await page.getByRole('button', { name: 'Add headquarter' }).click()
  let modal = page.locator('.modal.show')
  await chooseOption(modal, 'State', 'Gujarat')
  await modal.getByLabel('Headquarter Name').fill('Ahmedabad')
  await modal.getByLabel('Headquarter Code').fill('HQ-AMD')
  await modal.getByLabel('Address').fill('1 River Road')
  await modal.getByLabel('Pincode').fill('380001')
  await modal.getByLabel('Phone Number').fill('9000000101')
  await modal.getByLabel('Email').fill('ahmedabad@example.test')
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('.modal.show')).toHaveCount(0)
  const hqFilters = page.locator('.toolbar')
  await chooseOption(hqFilters, 'State', 'Bihar')
  await expect(page.locator('tbody tr', { hasText: 'Ahmedabad' })).toHaveCount(0)
  await chooseOption(hqFilters, 'State', 'Gujarat')
  await expect(page.locator('tbody tr', { hasText: 'Ahmedabad' })).toBeVisible()
  await page.getByRole('button', { name: 'Add headquarter' }).click()
  modal = page.locator('.modal.show')
  await chooseOption(modal, 'State', 'Bihar')
  await modal.getByLabel('Headquarter Name').fill('Patna')
  await modal.getByLabel('Headquarter Code').fill('HQ-PAT')
  await modal.getByLabel('Address').fill('2 River Road')
  await modal.getByLabel('Pincode').fill('800001')
  await modal.getByLabel('Phone Number').fill('9000000102')
  await modal.getByLabel('Email').fill('patna@example.test')
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('.modal.show')).toHaveCount(0)

  await page.goto('/sales-office/employees')
  await page.getByRole('button', { name: 'Add employee' }).click()
  modal = page.locator('.modal.show')
  await modal.getByLabel('First Name').fill('Gita')
  await modal.getByLabel('Last Name').fill('Manager')
  await modal.getByLabel('Designation').selectOption({ label: 'GM - General Manager' })
  await expect(modal.getByRole('group', { name: 'Reports to' })).toHaveCount(0)
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('tbody tr', { hasText: 'Gita Manager' })).toContainText('GM - General Manager')

  await page.getByRole('button', { name: 'Add employee' }).click()
  modal = page.locator('.modal.show')
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('button', { name: 'Edit employee' })).toBeVisible()

  await page.getByRole('button', { name: 'Edit employee' }).click()
  modal = page.locator('.modal.show')
  await modal.getByLabel('First Name').fill('Bina')
  await modal.getByLabel('Last Name').fill('Officer')
  await expect(modal.getByText('Type the code. It is not generated.')).toHaveCount(0)
  await modal.getByLabel('Employee Code').fill('BO-1')
  await modal.getByLabel('Email').fill('not-an-email')
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(modal.getByText('Enter a valid email address.')).toBeVisible()
  await modal.getByLabel('Email').fill('bina@example.test')
  await modal.getByLabel('Designation').selectOption({ label: 'BO - Business Officer' })
  const reports = modal.getByRole('group', { name: 'Reports to' })
  await expect(reports.getByLabel('GM - General Manager')).toBeVisible()
  await expect(reports.getByLabel('ZSM - Zonal Sales Manager')).toBeVisible()
  await expect(reports.getByLabel('ABM - Area Business Manager')).toBeVisible()
  await reports.getByLabel('GM - General Manager').selectOption({ label: 'Gita Manager' })
  await expect(reports.getByLabel('ZSM - Zonal Sales Manager')).toHaveValue('')
  await modal.getByLabel('Designation').selectOption({ label: 'ZSM - Zonal Sales Manager' })
  await expect(reports.getByLabel('GM - General Manager')).toBeVisible()
  await expect(reports.getByLabel('RBM - Region Business Manager')).toHaveCount(0)
  await modal.getByRole('checkbox', { name: 'Gujarat', exact: true }).check()
  await modal.getByRole('checkbox', { name: 'Bihar', exact: true }).check()
  await modal.getByRole('checkbox', { name: 'Ahmedabad (Gujarat)' }).check()
  await modal.getByRole('checkbox', { name: 'Patna (Bihar)' }).check()
  await modal.getByRole('checkbox', { name: 'Bihar', exact: true }).uncheck()
  await expect(modal.getByRole('checkbox', { name: 'Patna (Bihar)' })).toHaveCount(0)
  await expect(modal.getByRole('checkbox', { name: 'Ahmedabad', exact: true })).toBeChecked()
  await modal.getByRole('button', { name: 'Save' }).click()

  await expect(page.locator('.modal.show')).toHaveCount(0)
  const row = page.locator('tbody tr', { hasText: 'Bina Officer' })
  await expect(row).toContainText('BO-1')
  await expect(row).toContainText('ZSM - Zonal Sales Manager')
  await expect(row).toContainText('GM')
  await expect(row).toContainText('Gita Manager')
  await expect(row).toContainText('Gujarat')
  await expect(row).toContainText('Ahmedabad')
  await expect(row).not.toContainText('Patna')

  await page.getByRole('button', { name: 'Add employee' }).click()
  modal = page.locator('.modal.show')
  await modal.getByLabel('Employee Code').fill('BO-1')
  await modal.getByLabel('Email').fill('bina@example.test')
  await modal.getByRole('button', { name: 'Save' }).click()
  await expect(modal.getByText('This employee code is already used.')).toBeVisible()
  await expect(modal.getByText('This email is already used.')).toBeVisible()
  await modal.getByRole('button', { name: 'Cancel' }).click()

  const filters = page.locator('.toolbar')
  await filters.getByLabel('Designation').selectOption({ label: 'GM - General Manager' })
  await expect(page.locator('tbody tr', { hasText: 'Bina Officer' })).toHaveCount(0)
  await expect(page.locator('tbody tr', { hasText: 'Gita Manager' })).toHaveCount(1)

  await page.setViewportSize({ width: 390, height: 800 })
  await filters.getByLabel('Designation').selectOption({ label: 'All designations' })
  await filters.getByLabel('State').selectOption('Bihar')
  await expect(page.locator('tbody tr', { hasText: 'Bina Officer' })).toHaveCount(0)
  await filters.getByLabel('State').selectOption('Gujarat')
  await expect(page.locator('tbody tr', { hasText: 'Bina Officer' })).toHaveCount(1)
  await filters.getByLabel('HQ').selectOption('Ahmedabad')
  await expect(page.locator('tbody tr', { hasText: 'Bina Officer' })).toHaveCount(1)
  await filters.getByLabel('State').selectOption('All states')
  await filters.getByLabel('HQ').selectOption('All headquarters')
  const code = page.locator('td[data-label="Employee Code"]', { hasText: 'BO-1' })
  await expect(code).toBeVisible()

  await page.setViewportSize({ width: 1280, height: 800 })
  await page.getByRole('button', { name: /Account menu/ }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await signIn(page, USERS.sales)
  await expect(page).toHaveURL('/dashboard')
  await page.goto('/sales-office/employees')
  await expect(page.locator('tbody tr', { hasText: 'Bina Officer' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add employee' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit Bina Officer' })).toHaveCount(0)
})
